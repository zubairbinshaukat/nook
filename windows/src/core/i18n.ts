let islandLanguage: Language = "en";

export function setIslandLanguage(language: Language): boolean {
  if (islandLanguage === language) return false;
  islandLanguage = language;
  return true;
}

export function currentIslandLanguage(): Language {
  return islandLanguage;
}

export function tIsland(key: IslandTranslationKey, params: Record<string, string | number> = {}, language = islandLanguage): string {
  const template = ISLAND_DICTIONARIES[language][key] || ISLAND_ENGLISH[key];
  return template.replace(/\{([a-zA-Z][\w]*)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}

/** The context percentage template owns the percent sign, so pass it a localized number only. */
export function contextUsageLabel(value: number, language: Language): string {
  return tIsland("island.session.context", { percent: formatNumber(value, language) }, language);
}

export function usageSourceDescription(provider: "claude" | "codex", language: Language): string {
  return tIsland(provider === "codex" ? "island.usage.codexSource" : "island.usage.sourceUsage", {}, language);
}

